import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
const source = readFileSync(new URL('./src/services/openScalpFills.ts', import.meta.url), 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const exports = {};
new Function('exports', compiled)(exports);
const { openScalpFills } = exports;
const position = { symbol: 'NIFTYCE', product: 'NRML', exchange_segment: 'nse_fo', order_quantity: 65 };
const trade = (side, qty, price, minute, extra = {}) => ({ symbol: 'NIFTYCE', product: 'NRML', exchange_segment: 'nse_fo', side, qty, price, timestamp: `2026-10-30T10:${minute}:00+05:30`, order_id: minute, ...extra });
const history = [trade('BUY', 65, 100, '00'), trade('SELL', 65, 110, '01'), trade('BUY', 65, 120, '02')];
assert.deepEqual(openScalpFills(position, history).map(x => [x.price, x.quantity]), [[120, 65]]);
const added = [...history, trade('BUY', 65, 130, '03')];
assert.deepEqual(openScalpFills({ ...position, order_quantity: 130 }, added).map(x => x.price), [120, 130]);
assert.deepEqual(openScalpFills(position, [...added, trade('SELL', 65, 140, '04')]).map(x => x.price), [130]);
assert.deepEqual(openScalpFills({ ...position, order_quantity: 0 }, [...history, trade('SELL', 65, 125, '03')]), []);
assert.equal(openScalpFills({ ...position, order_quantity: 130 }, history), null);
assert.equal(openScalpFills(position, [trade('BUY', 65, 120, '02', { product: '' })]), null);
assert.equal(openScalpFills(position, [trade('BUY', 65, 120, '02', { timestamp: '' })]), null);
assert.deepEqual(openScalpFills({ ...position, order_quantity: -65 }, [trade('SELL', 65, 150, '00')]).map(x => x.price), [150]);
console.log('8 open-fill checks passed');
